//! Builds the data file used by the browser demo backend (development and UI tests
//! only). It runs the REAL engine over the hook fixtures in tests/fixtures and
//! records every update batch plus the final query results, so the UI demo shows
//! exactly what the engine would produce. Transcripts with token usage are written
//! to a temp dir for the demo; they are synthetic and only exist for this demo.
//!
//! cargo run -p ids-core --example export_demo -- apps/desktop/src/bridge/demo-data.json

use std::io::Write;
use std::path::PathBuf;

use ids_core::db::queries::{self as q, Filter};
use ids_core::engine::{Engine, EngineConfig};
use ids_core::event::Envelope;
use serde_json::{json, Value};

fn main() {
    let out = std::env::args().nth(1).expect("output path");
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let tmp = std::env::temp_dir().join("ids-demo");
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(tmp.join("sub")).unwrap();

    // Transcript timestamps inside the fixture's time window (base = 11:53:20Z).
    let ts = |secs_after_1153: i64| format!("2026-11-16T11:{:02}:{:02}Z", 53 + secs_after_1153 / 60, secs_after_1153 % 60);
    let main_t = tmp.join("main.jsonl");
    let mut f = std::fs::File::create(&main_t).unwrap();
    for i in 0..6 {
        writeln!(f, r#"{{"type":"assistant","timestamp":"{}","message":{{"id":"m{i}","model":"claude-opus-5","usage":{{"input_tokens":{},"output_tokens":{},"cache_read_input_tokens":{},"cache_creation_input_tokens":{}}}}}}}"#, ts(25 + i * 15), 1200 + i * 300, 400 + i * 90, 18000 + i * 2000, 900).unwrap();
    }
    let sub = |name: &str, model: &str, n: i64| {
        let p = tmp.join("sub").join(format!("{name}.jsonl"));
        let mut f = std::fs::File::create(&p).unwrap();
        for i in 0..n {
            writeln!(f, r#"{{"type":"assistant","timestamp":"{ts}","message":{{"id":"{name}-{i}","model":"{model}","usage":{{"input_tokens":{},"output_tokens":{},"cache_read_input_tokens":{}}}}}}}"#, 800 + i * 100, 200 + i * 50, 6000, ts = ts(40 + i * 12)).unwrap();
        }
        p
    };
    let explore_t = sub("explore", "claude-haiku-5", 4);
    let test_t = sub("test", "claude-sonnet-5", 3);
    let dev_t = sub("dev", "claude-sonnet-5", 5);

    let text = std::fs::read_to_string(root.join("tests/fixtures/session-multiagent.jsonl")).unwrap();
    let mut engine = Engine::in_memory(EngineConfig { transcript_roots: vec![tmp.clone()], ..Default::default() }).unwrap();
    let mut steps = vec![];
    let base = 1_794_830_000_000i64;
    for (i, line) in text.lines().enumerate() {
        let mut p: Value = serde_json::from_str(line).unwrap();
        // Point transcript paths at the demo transcripts.
        if p.get("transcript_path").is_some() {
            p["transcript_path"] = json!(main_t.to_string_lossy());
        }
        if let Some(a) = p.get("agent_transcript_path").and_then(Value::as_str) {
            let t = if a.contains("explore") { &explore_t } else if a.contains("test") { &test_t } else { &dev_t };
            p["agent_transcript_path"] = json!(t.to_string_lossy());
        }
        let env = Envelope { v: 1, id: format!("demo-{i}"), fired_at_ms: base + i as i64 * 4_000, payload: p };
        let out = engine.ingest(&env).unwrap();
        steps.push(serde_json::to_value(&out.updates).unwrap());
    }
    let c = engine.conn();
    let all = Filter { limit: Some(500), ..Default::default() };
    let sessions = q::sessions(c, &all).unwrap();
    let details: Vec<Value> = sessions.iter().map(|s| serde_json::to_value(q::session_detail(c, &s.session.id).unwrap()).unwrap()).collect();
    let agents = q::agents(c, &all).unwrap();
    let agent_details: Vec<Value> = agents.iter().map(|a| serde_json::to_value(q::agent_detail(c, &a.id).unwrap()).unwrap()).collect();
    let now = base + text.lines().count() as i64 * 4_000;
    let dashboard = json!({
        "overview": q::overview(c, None, now).unwrap(),
        "usageSeries": q::usage_timeseries(c, 0, now, 3_600_000).unwrap(),
        "activitySeries": q::activity_timeseries(c, 0, now, 60_000).unwrap(),
        "bySession": q::tokens_by_session(c, 0, 30).unwrap(),
        "byAgent": q::tokens_by_agent(c, 0, 30).unwrap(),
        "states": q::state_distribution(c, 0, now).unwrap(),
        "categories": q::category_distribution(c, 0).unwrap(),
        "from": base - 3_600_000,
        "to": now,
        "bucketMs": 3_600_000
    });
    let doc = json!({
        "note": "Generated by crates/ids-core/examples/export_demo.rs from tests/fixtures. Demo/development only.",
        "baseTime": base,
        "endTime": now,
        "steps": steps,
        "sessions": sessions,
        "sessionDetails": details,
        "agents": agents,
        "agentDetails": agent_details,
        "events": q::events(c, &all).unwrap(),
        "missions": q::missions(c, &all).unwrap(),
        "projects": q::projects(c).unwrap(),
        "dashboard": dashboard,
    });
    std::fs::write(&out, serde_json::to_vec(&doc).unwrap()).unwrap();
    println!("demo data written to {out}");
}
